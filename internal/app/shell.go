package app

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/yueliang13/proxrun"
)

var shellBlock = regexp.MustCompile(`(?ms)\n?# ─── (?:proxrun|simple-proxy) ───\nif \[ -r [^\n]*\n.*?^fi\n?`)

const fishMarker = "# Generated by proxrun.\n"

func detectShell() string {
	switch name := filepath.Base(os.Getenv("SHELL")); name {
	case "fish", "zsh":
		return name
	default:
		return "bash"
	}
}
func validShell(name string) bool { return name == "bash" || name == "zsh" || name == "fish" }
func (a *App) shell(args []string) int {
	name := detectShell()
	if len(args) > 1 {
		return a.fail(1, fmt.Errorf("用法: proxrun shell [bash|zsh|fish]"))
	}
	if len(args) == 1 {
		name = args[0]
	}
	if !validShell(name) {
		return a.fail(1, fmt.Errorf("不支持的 shell: %s", name))
	}
	asset := "lib/shell.sh"
	if name == "fish" {
		asset = "lib/shell.fish"
	}
	if _, err := a.Out.Write(proxrun.Asset(asset)); err != nil {
		return a.fail(1, err)
	}
	return 0
}
func shellQuote(value string) string { return "'" + strings.ReplaceAll(value, "'", "'\"'\"'") + "'" }
func fishQuote(value string) string {
	return "'" + strings.NewReplacer("\\", "\\\\", "'", "\\'").Replace(value) + "'"
}
func fishRC(c Config) string {
	dir := os.Getenv("XDG_CONFIG_HOME")
	if dir == "" {
		dir = filepath.Join(c.Home, ".config")
	}
	return filepath.Join(dir, "fish/conf.d/proxrun.fish")
}
func shellRC(c Config, name string) string {
	if name == "fish" {
		return fishRC(c)
	}
	if name == "zsh" {
		dir := os.Getenv("ZDOTDIR")
		if dir == "" {
			dir = c.Home
		}
		return filepath.Join(dir, ".zshrc")
	}
	return filepath.Join(c.Home, ".bashrc")
}
func writeShellRC(c Config, name string) error {
	path := shellRC(c, name)
	data, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if name == "fish" {
		if err == nil && !bytes.HasPrefix(data, []byte(fishMarker)) {
			return fmt.Errorf("%s 已存在且不是 proxrun 生成的文件，未覆盖", path)
		}
		script := fishQuote(filepath.Join(c.DataDir, "shell.fish"))
		block := fishMarker + "if test -r " + script + "\n    set -gx PROXRUN_BIN_DIR " + fishQuote(c.BinDir) + "\n    set -gx PROXRUN_DATA_DIR " + fishQuote(c.DataDir) + "\n    set -gx PROXRUN_CONFIG_DIR " + fishQuote(c.ConfigDir) + "\n    source " + script + "\nend\n"
		return atomicWrite(path, []byte(block), existingMode(path, 0644))
	}
	data = shellBlock.ReplaceAll(data, []byte("\n"))
	script := shellQuote(filepath.Join(c.DataDir, "shell.sh"))
	block := "\n# ─── proxrun ───\nif [ -r " + script + " ]; then\n  export PROXRUN_BIN_DIR=" + shellQuote(c.BinDir) + " PROXRUN_DATA_DIR=" + shellQuote(c.DataDir) + " PROXRUN_CONFIG_DIR=" + shellQuote(c.ConfigDir) + "; . " + script + "\nfi\n"
	return atomicWrite(path, append(data, []byte(block)...), existingMode(path, 0644))
}
func removeFishRC(c Config) error {
	path := fishRC(c)
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if bytes.HasPrefix(data, []byte(fishMarker)) {
		return os.Remove(path)
	}
	return nil
}
